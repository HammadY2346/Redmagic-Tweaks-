    /**
     * Our own pack (not from nubia-ly): original rounded / filled glyphs in a One UI 8 style, res/drawable/oui8_<key>.xml,
     * generated by tools/oui8_icons.py. Besides the shared keys it has Wi-Fi "no internet" (wifi_noinet_0..4), mobile
     * "no data / no service" (signal_cut_0..4) and the roaming "R" (roaming); the nubia-ly packs keep stock for those.
     */
    public static final int PACK_ONE_UI8 = 17;

    /** Drawable resource name of {@code key} in {@code pack}. */
    public static String packArtName(int pack, String key) {
        return pack == PACK_ONE_UI8 ? "oui8_" + key : "iconpack_" + pack + "_" + key;
    }

    /** Keys only the One UI 8 pack draws; asking another pack for them is skipped instead of logged as missing. */
    public static boolean oneUi8Only(String key) {
        return key != null && (key.startsWith("wifi_noinet_") || key.startsWith("signal_cut_") || key.equals("roaming"));
    }
